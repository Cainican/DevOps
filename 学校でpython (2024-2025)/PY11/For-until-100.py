# kasan keika wo kakunou suru hensuu
sum=0

# kuri kaeshi nagara kasansuru
for i in range(1,101):
	sum=sum+i

# goukei (sum) no shutsuryoku
print("1 kara 100 made no goukei ha {0}desu.".format(sum))